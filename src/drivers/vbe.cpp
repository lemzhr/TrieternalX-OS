void vbe_init(multiboot_info* mbi)
{
    vbe_active = false;

    if ((mbi->flags & (1 << 12)) == 0) return;

    fb_addr = (uint32_t*)(uint32_t)mbi->framebuffer_addr;
    fb_pitch = mbi->framebuffer_pitch;
    fb_width = mbi->framebuffer_width;
    fb_height = mbi->framebuffer_height;
    fb_bpp = mbi->framebuffer_bpp;

    if (fb_bpp != 32) return;

    vbe_active = true;

    vbe_clear(0x001B4B);

    console_cols = fb_width / 8;
    console_rows = fb_height / 8;
    console_x = 0;
    console_y = 0;
}

bool vbe_is_active()
{
    return vbe_active;
}

uint32_t vbe_get_width()
{
    return fb_width;
}

uint32_t vbe_get_height()
{
    return fb_height;
}

void* vbe_get_framebuffer_addr()
{
    return (void*)fb_addr;
}

uint32_t vbe_get_framebuffer_pitch()
{
    return fb_pitch;
}

void vbe_putpixel(int x, int y, uint32_t color)
{
    if (!vbe_active) return;
    if (x < 0 || (uint32_t)x >= fb_width || y < 0 || (uint32_t)y >= fb_height) return;

    uint32_t* pixel = (uint32_t*)((uint8_t*)fb_addr + y * fb_pitch + x * 4);
    *pixel = color;
}

void vbe_clear(uint32_t color)
{
    if (!vbe_active) return;

    for (uint32_t y = 0; y < fb_height; y++)
    {
        uint32_t* line = (uint32_t*)((uint8_t*)fb_addr + y * fb_pitch);
        for (uint32_t x = 0; x < fb_width; x++)
        {
            line[x] = color;
        }
    }
}

void vbe_draw_rect(int x, int y, int w, int h, uint32_t color)
{
    if (!vbe_active) return;

    for (int cy = y; cy < y + h; cy++)
    {
        if (cy < 0 || (uint32_t)cy >= fb_height) continue;
        uint32_t* line = (uint32_t*)((uint8_t*)fb_addr + cy * fb_pitch);
        for (int cx = x; cx < x + w; cx++)
        {
            if (cx < 0 || (uint32_t)cx >= fb_width) continue;
            line[cx] = color;
        }
    }
}

void vbe_draw_line(int x1, int y1, int x2, int y2, uint32_t color)
{
    if (!vbe_active) return;

    int dx = (x2 - x1 >= 0) ? (x2 - x1) : (x1 - x2);
    int dy = (y2 - y1 >= 0) ? (y2 - y1) : (y1 - y2);
    int sx = (x1 < x2) ? 1 : -1;
    int sy = (y1 < y2) ? 1 : -1;
    int err = dx - dy;

    while (true)
    {
        vbe_putpixel(x1, y1, color);
        if (x1 == x2 && y1 == y2) break;
        int e2 = 2 * err;
        if (e2 > -dy)
        {
            err -= dy;
            x1 += sx;
        }
        if (e2 < dx)
        {
            err += dx;
            y1 += sy;
        }
    }
}

void vbe_draw_char(int x, int y, char c, uint32_t color)
{
    if (!vbe_active) return;
    if (c < 32 || c > 126) return;

    int font_idx = c - 32;

    for (int row = 0; row < 8; row++)
    {
        uint8_t bits = font8x8[font_idx][row];
        for (int col = 0; col < 8; col++)
        {

            if (bits & (0x80 >> col))
            {
                vbe_putpixel(x + col, y + row, color);
            }
        }
    }
}

void vbe_draw_string(int x, int y, const char* str, uint32_t color)
{
    int i = 0;
    while (str[i] != '\0')
    {
        vbe_draw_char(x + (i * 8), y, str[i], color);
        i++;
    }
}

void vbe_console_write(const char* str)
{
    int i = 0;
    while (str[i] != '\0')
    {
        vbe_console_putchar(str[i]);
        i++;
    }
}

void vbe_console_putchar(char c)
{
    if (!vbe_active) return;

    if (c == '\n')
    {
        console_x = 0;
        console_y++;
    }
    else if (c == '\r')
    {
        console_x = 0;
    }
    else if (c == '\b')
    {
        if (console_x > 0)
        {
            console_x--;
            vbe_draw_rect(console_x * 8, console_y * 8, 8, 8, console_bg);
        }
    }
    else if (c == '\t')
    {
        console_x = (console_x + 8) & ~7;
    }
    else
    {

        vbe_draw_rect(console_x * 8, console_y * 8, 8, 8, console_bg);
        vbe_draw_char(console_x * 8, console_y * 8, c, console_fg);
        console_x++;
    }

    if (console_x >= console_cols)
    {
        console_x = 0;
        console_y++;
    }

    if (console_y >= console_rows)
    {
        uint8_t* fb_bytes = (uint8_t*)fb_addr;

        for (int y = 0; y < 592; y++)
        {
            uint32_t* dest = (uint32_t*)(fb_bytes + y * fb_pitch);
            uint32_t* src = (uint32_t*)(fb_bytes + (y + 8) * fb_pitch);
            for (uint32_t x = 0; x < fb_width; x++)
            {
                dest[x] = src[x];
            }
        }

        vbe_draw_rect(0, 592, fb_width, 8, console_bg);

        console_y = console_rows - 1;
    }
}

void vbe_console_clear()
{
    if (!vbe_active) return;
    vbe_clear(console_bg);
    console_x = 0;
    console_y = 0;
}

void vbe_console_set_color(uint32_t fg, uint32_t bg)
{
    console_fg = fg;
    console_bg = bg;
}
